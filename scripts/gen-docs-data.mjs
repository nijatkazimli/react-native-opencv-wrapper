/**
 * Generates docs/data.js from the library source. Reads the exported `<id>Doc`
 * constant (typed `OpDoc`) from each src/ops/<id>.ts, plus the non-per-op
 * metadata in docs-meta.mjs and the package name/version/repo from package.json.
 *
 * Parsing is a static TypeScript AST walk (no code execution of the op files);
 * only the doc object literal — which is pure data — is evaluated. Run via
 * `npm run docs:gen`, which also prettier-formats the output.
 */
import ts from "typescript";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  opencvBlurb,
  imageFormats,
  errorCodes,
  categories,
} from "./docs-meta.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const opsDir = path.join(root, "src", "ops");
const outFile = path.join(root, "docs", "data.js");

const pkg = JSON.parse(
  fs.readFileSync(path.join(root, "package.json"), "utf8"),
);

/** Pull the `OpDoc`-typed object literal out of an op file and evaluate it. */
function extractDoc(file) {
  const src = fs.readFileSync(file, "utf8");
  const sf = ts.createSourceFile(
    file,
    src,
    ts.ScriptTarget.Latest,
    /* setParentNodes */ true,
  );

  let initText = null;
  sf.forEachChild((node) => {
    if (initText || !ts.isVariableStatement(node)) return;
    for (const decl of node.declarationList.declarations) {
      const t = decl.type;
      if (
        t &&
        ts.isTypeReferenceNode(t) &&
        t.typeName.getText(sf) === "OpDoc" &&
        decl.initializer
      ) {
        initText = decl.initializer.getText(sf);
        return;
      }
    }
  });

  if (!initText) return null;
  // The initializer is a plain object literal (strings + template literals).

  return new Function(`return (${initText});`)();
}

const ops = [];
for (const f of fs.readdirSync(opsDir).sort()) {
  if (!f.endsWith(".ts") || f === "index.ts" || f === "docTypes.ts") continue;
  const id = f.replace(/\.ts$/, "");
  const doc = extractDoc(path.join(opsDir, f));
  if (!doc) {
    console.warn(`warning: no OpDoc found in ${f}`);
    continue;
  }
  ops.push({ id, ...doc });
}

const catOrder = new Map(categories.map((c, i) => [c.id, i]));
ops.sort((a, b) => {
  const ca = catOrder.has(a.category) ? catOrder.get(a.category) : 999;
  const cb = catOrder.has(b.category) ? catOrder.get(b.category) : 999;
  if (ca !== cb) return ca - cb;
  return a.name.localeCompare(b.name);
});

const repoUrl = (pkg.repository?.url || "")
  .replace(/^git\+/, "")
  .replace(/\.git$/, "")
  .replace(/#.*$/, "");
const repo = repoUrl.replace(/^https?:\/\/github\.com\//, "");

const data = {
  meta: {
    name: pkg.name,
    version: pkg.version,
    opencv: opencvBlurb,
    repo,
    repoUrl,
  },
  imageFormats,
  errorCodes,
  categories,
  ops,
};

const header = `/**
 * Documentation data for ${pkg.name}.
 *
 * GENERATED by scripts/gen-docs-data.mjs from the library source
 * (src/ops/*, scripts/docs-meta.mjs, package.json). Do not edit by hand —
 * run \`npm run docs:gen\` to regenerate. Consumed by app.js to render the site.
 */
`;

fs.writeFileSync(
  outFile,
  `${header}window.OPENCV_DOCS = ${JSON.stringify(data, null, 2)};\n`,
);

console.log(`wrote ${path.relative(root, outFile)} (${ops.length} ops)`);
